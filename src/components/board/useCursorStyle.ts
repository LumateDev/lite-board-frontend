function encode(svg: string, color: string) {
  const colored = svg
    .replace(/fill="[^"]*"/g, '')
    .replace(/<path/g, `<path fill="${color}"`)
    .replace(/<rect/g, `<rect fill="${color}"`)
    .replace(/<g fill="none"/g, `<g fill="${color}"`)

  const encoded = encodeURIComponent(colored)
    .replace(/\(/g, '%28')
    .replace(/\)/g, '%29')
  return `url("data:image/svg+xml,${encoded}") 4 4, auto`
}

